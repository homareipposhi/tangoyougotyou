import { readdir, mkdir, writeFile } from 'node:fs/promises';
import { join, posix } from 'node:path';

async function findQuestionFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async entry => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return findQuestionFiles(path);
    return entry.isFile() && entry.name.endsWith('.js') ? [posix.join(...path.split(/\\|\//))] : [];
  }));
  return nested.flat();
}

const files = (await findQuestionFiles('subjects')).sort();
await mkdir('js', { recursive: true });
await writeFile('js/generated-manifest.js', `/* This file is generated by GitHub Actions. Do not edit manually. */\nconst MANIFEST = ${JSON.stringify(files, null, 2)};\n`);
