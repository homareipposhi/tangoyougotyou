import { readdir, mkdir, writeFile } from 'node:fs/promises';
const files = (await readdir('subjects', { withFileTypes: true }))
  .filter(entry => entry.isFile() && entry.name.endsWith('.js'))
  .map(entry => `subjects/${entry.name}`)
  .sort();
await mkdir('js', { recursive: true });
await writeFile('js/generated-manifest.js', `/* This file is generated by GitHub Actions. Do not edit manually. */\nconst MANIFEST = ${JSON.stringify(files, null, 2)};\n`);
